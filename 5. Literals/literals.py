'''
What are Literals?

Literals are direct constant values explicitly written in code.
Variables may hold literals, results of computations, or input data.
Literals are synonymous with constants.

Example: a = 10 (10 is literal), vs c = a + b (c receives a computed value, not a literal).

'''

# Integer Literals:

a = 10
b = 123_654_876 #Underscore is used to separate digits
print(a) # 10
print(b) # 123654876

# Float Literals:

c = 10.5
d = 123.654_876
print(c) # 10.5
print(d) # 123.654876

# Boolean Literals:

e = True
f = False
print(e) # True
print(f) # False

# Complex Literals:

g = 3 + 4j
print(g) # (3+4j)

# String Literals:

h = 'Hello'
i = "Alexa"
print(h) # Hello
print(i) # Alexa